async function resolveDesktopRemoteRuntimeNetwork(
  target: RemoteTarget,
): Promise<RemoteRuntimeNetworkOptions | undefined> {
  if (target.kind !== "wsl") {
    return undefined;
  }
  const settingService = activeServices?.getOptional(ISettingService);
  if (!settingService) {
    return undefined;
  }
  try {
    const settings = await settingService.get();
    return {
      authoritative: true,
      httpProxy: settings.httpProxy,
      noProxy: settings.httpProxyNoProxy,
    };
  } catch {
    // On settings-read failure keep the legacy remote behavior; network hardening must not block WSL workspaces.
    return undefined;
  }
}

