import { resolveToolCallIdentity } from "@/lib/toolIdentity.js";
import type { ToolCallBlockRenderContext } from "@/ToolCallBlocks/shared.js";

export function resolveToolCallRenderer(context: ToolCallBlockRenderContext) {
  if (context.toolCallNode.toolCall.kind === "changesGroup") {
    return ChangesGroupToolCallBlock;
  }
  if (context.toolCallNode.toolCall.kind === "executeGroup") {
    return ExecuteGroupToolCallBlock;
  }
  if (context.toolCallNode.toolCall.kind === "cuaGroup") {
    return CuaGroupToolCallBlock;
  }
  if (isCuaToolCall(context.toolCallNode.toolCall)) {
    return CuaToolCallBlock;
  }

  const identity = resolveToolCallIdentity(context.toolCallNode.toolCall);

  // The two reusable-workflow tools dispatch by **tool name** first, deliberately before the family, for two reasons:
  // they are not in the shared known-tools table yet (identity resolves unknown -> raw JSON fallback card);
  // and once registered under the workflow family, the fallback below would render them as CreateWorkflow cards.
  // Name-first matching keeps both worlds correct.
  if (isSaveWorkflowToolCall(context.toolCallNode.toolCall)) {
    return SaveWorkflowToolCallBlock;
  }
  if (isListSavedWorkflowsToolCall(context.toolCallNode.toolCall)) {
    return ListSavedWorkflowsToolCallBlock;
  }

  // The three observability workflow tools likewise dispatch by name before family: not in the known-tools table (identity
  // unknown -> raw JSON fallback card), and the workflow-family fallback is the CreateWorkflow card;
  // name-first matching keeps the pre-/post-registration worlds correct (same reason as workflowToolNames).
  if (isGetWorkflowRunToolCall(context.toolCallNode.toolCall)) {
    return GetWorkflowRunToolCallBlock;
  }
  if (isListWorkflowRunsToolCall(context.toolCallNode.toolCall)) {
    return ListWorkflowRunsToolCallBlock;
  }
  if (isEvalWorkflowSnippetToolCall(context.toolCallNode.toolCall)) {
    return EvalWorkflowSnippetToolCallBlock;
  }
  // The ResumeWorkflowRun entry likewise claims by name (as above: not in the known-tools table, and the workflow-family
  // fallback is the CreateWorkflow card - the resume card must claim its name before the family).
  if (isResumeWorkflowRunToolCall(context.toolCallNode.toolCall)) {
    return ResumeWorkflowRunToolCallBlock;
  }
  // The model catalog likewise claims by name; otherwise the fallback card would
  // dump the providerId-leading <models> text straight into the chat.
  if (isListModelsToolCall(context.toolCallNode.toolCall)) {
    return ListModelsToolCallBlock;
  }

  // The two escalation tools likewise dispatch by name before family: not in the known-tools table (identity
  // unknown -> raw JSON fallback card), and the workflow-family fallback is the CreateWorkflow card; name-first keeps
  // both worlds correct. escalate (a subagent asks) and ResolveWorkflowQuestion (the main agent answers)
  // have entirely different card faces; each claims its own name.
  if (isEscalateToolCall(context.toolCallNode.toolCall)) {
    return EscalateToolCallBlock;
  }
  if (isResolveWorkflowQuestionToolCall(context.toolCallNode.toolCall)) {
    return ResolveWorkflowQuestionToolCallBlock;
  }

  // The host Node REPL also registers via MCP and thus carries the mcp_tool presentation.
  // The generic MCP branch would swallow the code, error stack and artifact-specific interactions;
  // keep the Node REPL renderer by trusted tool identity first, then let remaining MCP tools use the generic presentation.
  if (identity.family === "node-repl") {
    return NodeReplToolCallBlock;
  }
  if (readMcpToolPresentation(context)) {
    return McpToolCallBlock;
  }

  // The tool-name set here is fixed. Regex-scanning kind/title would
  // read the Write inside TodoWrite as a file write. Parse the fixed tool identity first, then dispatch by family;
  // legacy-projected tool shapes are handled by the identity resolver.
  switch (identity.family) {
    case "plan-guidance":
      return PlanGuidanceToolCallBlock;
    case "agent":
      return AgentToolCallBlock;
    case "todo":
      return TodoToolCallBlock;
    case "ask-user-question":
      return AskQuestionToolCallBlock;
    case "message":
      return identity.toolName === "RespondToCoordinator"
        ? RespondToCoordinatorToolCallBlock
        : SendMessageToolCallBlock;
    case "task-control":
      return identity.toolName === "TaskOutput" ? TaskOutputToolCallBlock : TaskStopToolCallBlock;
    case "skill":
      return SkillToolCallBlock;
    case "workflow":
      // Within a family, dispatch by tool name (same precedent as message -> RespondToCoordinator):
      // the two workflow tool cards differ entirely - one is the script/graph, the other the actor-submitted result.
      return identity.toolName === "submit_result"
        ? SubmitResultToolCallBlock
        : CreateWorkflowToolCallBlock;
    case "session-context":
      return ReadSessionContextToolCallBlock;
    case "file-read":
      return ReadToolCallBlock;
    case "file-write":
      return EditToolCallBlock;
    case "explore":
      return ExploreToolCallBlock;
    case "switch-mode":
      return SwitchModeToolCallBlock;
    case "search":
      return SearchToolCallBlock;
    case "shell":
      return ExecuteToolCallBlock;
    case "goal":
      return GoalToolCallBlock;
    default:
      return FallbackToolCallBlock;
  }
}
