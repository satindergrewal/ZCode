// With defaultEnabled: true in an official plugin definition, join `<name>@<marketplace>` entries
// and hand them to the adapter to default-enable absent explicit user config (content-only plugins).
// Note: every plugin-resolution entrypoint (CLI subcommand resolveZCodePlugins, startup resolveStartupPlugins)
// must pass this set to discoverNodePluginsSync, or defaultEnabled never applies.
export const DEFAULT_ENABLED_OFFICIAL_PLUGIN_IDS: ReadonlySet<string> = new Set(
  OFFICIAL_PLUGIN_DEFINITIONS.filter((definition) => definition.defaultEnabled).map(
    (definition) => `${definition.name}@${ZCODE_OFFICIAL_PLUGIN_MARKETPLACE}`,
  ),
);

export function resolveOfficialPluginHostMcpServerNames(pluginId: string): string[] {
  const definition = OFFICIAL_PLUGIN_DEFINITIONS.find(
    (candidate) => `${candidate.name}@${ZCODE_OFFICIAL_PLUGIN_MARKETPLACE}` === pluginId,
  );
  return definition?.hostMcpServerNames ? [...definition.hostMcpServerNames] : [];
}

/**
 * For official plugins injected by the host CLI (e.g. browser-use's `node_repl`), MCP server names carry no `plugin:` prefix;
 * attributing a resource to its plugin requires a reverse lookup of the owning official plugin.
 */
export function resolveOfficialPluginNameByHostMcpServerName(
  serverName: string,
): string | undefined {
  return OFFICIAL_PLUGIN_DEFINITIONS.find((definition) =>
    definition.hostMcpServerNames?.includes(serverName),
  )?.name;
}
